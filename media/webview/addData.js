const vscode = acquireVsCodeApi();
const $ = (id) => document.getElementById(id);
const h = (s) => String(s ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
let cols = [], timer;
const entries = () => Object.fromEntries(cols.filter((c) => !c.generated).map((c, i) => [c.name, { value: $('v' + cols.indexOf(c)).value, isNull: $('n' + cols.indexOf(c)).checked }]));
const send = (type) => vscode.postMessage({ type, entries: entries() });
function row(c, i) {
  if (c.generated) return '<div class="row skip"><label>' + h(c.name) + '<small>' + h(c.type) + '</small></label><span class="nl">generated by the server</span><span></span></div>';
  const ph = c.default !== undefined ? 'default: ' + c.default : c.nullable ? 'empty = default / NULL not set' : 'required';
  return '<div class="row"><label for="v' + i + '">' + h(c.name) + '<small>' + h(c.type) + (c.nullable ? '' : ' · not null') + '</small></label>'
    + '<input id="v' + i + '" type="text" spellcheck="false" autocomplete="off" placeholder="' + h(ph) + '">'
    + (c.nullable ? '<label class="nl"><input id="n' + i + '" type="checkbox"> NULL</label>' : '<span><input id="n' + i + '" type="checkbox" hidden></span>') + '</div>';
}
function changed(e) {
  if (e.target.type === 'checkbox') { const v = $('v' + e.target.id.slice(1)); v.disabled = e.target.checked; if (e.target.checked) v.value = ''; }
  clearTimeout(timer); timer = setTimeout(() => send('change'), 120);
}
document.addEventListener('input', changed);
$('insert')?.addEventListener('click', () => send('insert'));
$('openSql').addEventListener('click', () => send('open'));
window.addEventListener('message', ({ data: m }) => {
  if (m.type === 'init') {
    cols = m.columns;
    $('cols').innerHTML = cols.map(row).join('');
    send('change');
  } else if (m.type === 'script') {
    $('preview').textContent = m.sql || '';
    $('errors').innerHTML = m.errors.map((e) => '<li>' + h(e) + '</li>').join('');
    for (const id of ['insert', 'openSql']) if ($(id)) $(id).disabled = !m.sql;
  } else if (m.type === 'inserted') {
    $('cols').innerHTML = cols.map(row).join('');
    $('status').textContent = m.text; $('status').className = '';
    send('change');
  } else if (m.type === 'status') {
    $('status').textContent = m.text; $('status').className = m.error ? 'err' : '';
  }
});
vscode.postMessage({ type: 'ready' });
