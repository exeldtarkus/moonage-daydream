import { randomBytes } from 'crypto';
import { esc } from './resultsHtml';

/**
 * form Add Data (tab): satu baris isian per kolom, script INSERT live di bawah.
 * ext -> page: { type: 'init', columns: {name, type, nullable, generated, default}[] } | { type: 'script', sql, errors } | { type: 'status', text, error? } | { type: 'inserted', text }
 * page -> ext: { type: 'ready' } | { type: 'change' | 'insert' | 'open', entries: { [kolom]: { value, isNull } } }
 */
export function addDataHtml(cspSource: string, t: { conn: string; table: string; type: string }, readOnly: boolean): string {
  const nonce = randomBytes(16).toString('base64');
  return `<!DOCTYPE html>
<html>
<head>
<meta charset="UTF-8">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src ${cspSource} 'unsafe-inline'; script-src 'nonce-${nonce}';">
<style>
  :root {
    --fg: var(--vscode-foreground); --muted: var(--vscode-descriptionForeground); --line: var(--vscode-panel-border, #8884);
    --bg: var(--vscode-editor-background); --raise: var(--vscode-sideBar-background, var(--bg)); --focus: var(--vscode-focusBorder);
    --mono: var(--vscode-editor-font-family, monospace); --err: var(--vscode-errorForeground, #f48771);
  }
  * { box-sizing: border-box; }
  body { margin: 0; padding: 18px 20px 24px; color: var(--fg); background: var(--bg); font-family: var(--vscode-font-family); font-size: 13px; max-width: 900px; }
  h1 { margin: 0; font-size: 20px; font-weight: 600; }
  .where { margin: 2px 0 16px; color: var(--muted); }
  .ro { color: var(--vscode-editorWarning-foreground); margin-bottom: 12px; }
  .row { display: grid; grid-template-columns: minmax(130px, 220px) minmax(0, 1fr) auto; gap: 4px 12px; align-items: center; margin: 6px 0; }
  .row label { overflow-wrap: anywhere; }
  .row small { display: block; color: var(--muted); font-family: var(--mono); }
  .row.skip { opacity: .6; }
  input[type=text] { width: 100%; max-width: 460px; height: 28px; font: inherit; padding: 0 8px; border-radius: 3px; color: var(--vscode-input-foreground);
    background: var(--vscode-input-background); border: 1px solid var(--vscode-input-border, color-mix(in srgb, var(--line) 80%, transparent)); }
  input[type=text]:focus { outline: none; border-color: var(--focus); }
  input[type=text]:disabled { opacity: .5; }
  .nl { color: var(--muted); white-space: nowrap; }
  :focus-visible { outline: 1px solid var(--focus); outline-offset: 1px; }
  h2 { font-size: 12px; font-weight: 600; text-transform: uppercase; letter-spacing: .04em; color: var(--muted); margin: 20px 0 6px; }
  #errors { margin: 0 0 6px; padding-left: 18px; color: var(--err); }
  #errors:empty { display: none; }
  pre { margin: 0; padding: 10px 12px; min-height: 40px; border-radius: 4px; background: var(--raise); border: 1px solid var(--line);
    font-family: var(--mono); white-space: pre-wrap; overflow-wrap: anywhere; }
  .actions { display: flex; flex-wrap: wrap; gap: 8px; margin-top: 14px; align-items: center; }
  button { font: inherit; height: 28px; padding: 0 14px; border-radius: 4px; cursor: pointer; border: 1px solid var(--vscode-button-border, transparent);
    color: var(--vscode-button-secondaryForeground); background: var(--vscode-button-secondaryBackground); }
  button:hover:not(:disabled) { background: var(--vscode-button-secondaryHoverBackground); }
  button.primary { color: var(--vscode-button-foreground); background: var(--vscode-button-background); }
  button.primary:hover:not(:disabled) { background: var(--vscode-button-hoverBackground); }
  button:disabled { opacity: .45; cursor: default; }
  #status { color: var(--muted); }
  #status.err { color: var(--err); }
  @media (max-width: 560px) { .row { grid-template-columns: 1fr; } body { padding: 14px; } }
</style>
</head>
<body>
<h1>Add Data</h1>
<p class="where">${esc(t.conn)} · ${esc(t.table)} · ${esc(t.type)}</p>
${readOnly ? '<p class="ro">Read-only connection: rows cannot be inserted here, use Open in SQL Editor to get the script.</p>' : ''}
<div id="cols"></div>
<h2>Script</h2>
<ul id="errors"></ul>
<pre id="preview"></pre>
<div class="actions">
  ${readOnly ? '' : '<button id="insert" class="primary" disabled>Insert</button>'}
  <button id="openSql" disabled>Open in SQL Editor</button>
  <span id="status" role="status"></span>
</div>
<script nonce="${nonce}">
const vscode = acquireVsCodeApi();
const $ = (id) => document.getElementById(id);
const h = (s) => String(s ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
let cols = [], timer;
const entries = () => Object.fromEntries(cols.filter((c) => !c.generated).map((c, i) => [c.name, { value: $('v' + cols.indexOf(c)).value, isNull: $('n' + cols.indexOf(c)).checked }]));
const send = (type) => vscode.postMessage({ type, entries: entries() });
function row(c, i) {
  if (c.generated) return '<div class="row skip"><label>' + h(c.name) + '<small>' + h(c.type) + '</small></label><span class="nl">generated by the server</span><span></span></div>';
  const ph = c.default !== undefined ? 'default: ' + c.default : c.nullable ? 'empty = default / NULL not set' : 'required';
  return '<div class="row"><label for="v' + i + '">' + h(c.name) + '<small>' + h(c.type) + (c.nullable ? '' : ' · not null') + '</small></label>'
    + '<input id="v' + i + '" type="text" spellcheck="false" autocomplete="off" placeholder="' + h(ph) + '">'
    + (c.nullable ? '<label class="nl"><input id="n' + i + '" type="checkbox"> NULL</label>' : '<span><input id="n' + i + '" type="checkbox" hidden></span>') + '</div>';
}
function changed(e) {
  if (e.target.type === 'checkbox') { const v = $('v' + e.target.id.slice(1)); v.disabled = e.target.checked; if (e.target.checked) v.value = ''; }
  clearTimeout(timer); timer = setTimeout(() => send('change'), 120);
}
document.addEventListener('input', changed);
$('insert')?.addEventListener('click', () => send('insert'));
$('openSql').addEventListener('click', () => send('open'));
window.addEventListener('message', ({ data: m }) => {
  if (m.type === 'init') {
    cols = m.columns;
    $('cols').innerHTML = cols.map(row).join('');
    send('change');
  } else if (m.type === 'script') {
    $('preview').textContent = m.sql || '';
    $('errors').innerHTML = m.errors.map((e) => '<li>' + h(e) + '</li>').join('');
    for (const id of ['insert', 'openSql']) if ($(id)) $(id).disabled = !m.sql;
  } else if (m.type === 'inserted') {
    $('cols').innerHTML = cols.map(row).join('');
    $('status').textContent = m.text; $('status').className = '';
    send('change');
  } else if (m.type === 'status') {
    $('status').textContent = m.text; $('status').className = m.error ? 'err' : '';
  }
});
vscode.postMessage({ type: 'ready' });
</script>
</body>
</html>`;
}
